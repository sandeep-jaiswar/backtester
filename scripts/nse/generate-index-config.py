"""
Generates src/lib/nse/generated/index-config.ts from nselib's nse_config.py.

Usage: python3 -I scripts/nse/generate-index-config.py <path/to/nselib/indices/nse_config.py>

Uses ast.parse only: the nselib source is read, never executed.
"""
import ast
import json
import sys
from pathlib import Path

src_path = Path(sys.argv[1])
tree = ast.parse(src_path.read_text(encoding="utf-8"))

categories = {}
for node in tree.body:
    if not isinstance(node, ast.ClassDef):
        continue
    entry = {}
    for stmt in node.body:
        if isinstance(stmt, ast.Assign) and isinstance(stmt.targets[0], ast.Name):
            entry[stmt.targets[0].id] = ast.literal_eval(stmt.value)
    categories[node.name] = entry

out = [
    "// GENERATED by scripts/nse/generate-index-config.py from nselib 2.4.7 indices/nse_config.py. Do not edit by hand.",
    "",
]
for name, data in categories.items():
    key = name[len("Nifty"):]
    out.append(f"export const {name} = {{")
    out.append(f"  indicesList: {json.dumps(data['indices_list'], ensure_ascii=False)} as const,")
    out.append(f"  constituentUrls: {json.dumps(data['index_constituent_list_urls'], indent=2, ensure_ascii=False)},")
    out.append(f"  factsheetUrls: {json.dumps(data['index_factsheet_urls'], indent=2, ensure_ascii=False)},")
    out.append("} as const;")
    out.append("")
out.append("export const INDEX_CATEGORIES = {")
for name in categories:
    out.append(f"  {name[len('Nifty'):]!r}: {name},".replace("'", '"'))
out.append("} as const;")
out.append("")

dest = Path(__file__).resolve().parents[2] / "src/lib/nse/generated/index-config.ts"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out), encoding="utf-8")
print("wrote", dest, "categories:", list(categories))
